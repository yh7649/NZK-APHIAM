@dataclass(frozen=True)
class SheetSpec:
    """Expected layout and generation-boundary mapping for one workbook sheet."""

    plant_name: str
    headers: tuple[str, ...]
    outlet_column: int
    pollutant_columns: dict[str, int]
    outlet_boundaries: dict[str, str]
    unit_column: int | None = None
    outlet_units: dict[str, str | None] | None = None


def _same_boundary(outlets: tuple[str, ...], boundary: str) -> dict[str, str]:
    return dict.fromkeys(outlets, boundary)


